import AppKit
import Testing

/// Uses private named pasteboards, never the user's real clipboard.
@MainActor
struct ClipboardCaptureTests {
    private let pasteboard = NSPasteboard(name: .init("superdock-test-\(UUID().uuidString)"))

    private func put(_ string: String, extraTypes: [NSPasteboard.PasteboardType] = []) {
        pasteboard.clearContents()
        pasteboard.declareTypes([.string] + extraTypes, owner: nil)
        pasteboard.setString(string, forType: .string)
        for type in extraTypes { pasteboard.setData(Data(), forType: type) }
    }

    @Test(arguments: ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"])
    func passwordManagerItemsAreNeverRead(marker: String) {
        put("hunter2", extraTypes: [.init(marker)])
        #expect(ClipboardCapture.read(pasteboard) == nil)
    }

    @Test func plainTextIsCaptured() {
        put("hello world")
        #expect(ClipboardCapture.read(pasteboard) == .text("hello world"))
    }

    @Test func whitespaceOnlyIsIgnored() {
        put("  \n ")
        #expect(ClipboardCapture.read(pasteboard) == nil)
    }

    @Test func filesWinOverTheirNameString() {
        pasteboard.clearContents()
        pasteboard.writeObjects([URL(fileURLWithPath: "/tmp/a.txt") as NSURL])
        #expect(ClipboardCapture.read(pasteboard) == .files([URL(fileURLWithPath: "/tmp/a.txt")]))
    }

    @Test(arguments: [
        ("#ff8800", ClipboardCapture.Content.color("#ff8800")),
        ("#FFF", .color("#FFF")),
        ("123456", .text("123456")),                       // no # → just a number
        ("#ggg", .text("#ggg")),
        ("https://example.com/a?b=1", .link("https://example.com/a?b=1")),
        ("mailto:hi@example.com", .link("mailto:hi@example.com")),
        ("see https://example.com", .text("see https://example.com")),
        ("ftp://example.com", .text("ftp://example.com"))
    ])
    func classifies(input: String, expected: ClipboardCapture.Content) {
        #expect(ClipboardCapture.classify(input) == expected)
    }
}

@MainActor
struct ClipboardStoreTests {
    private let folder = FileManager.default.temporaryDirectory.appending(path: "superdock-clip-\(UUID().uuidString)")

    @Test func recopyMovesToTopWithoutDuplicating() {
        let store = ClipboardStore(folder: folder)
        store.add(.text("a"), sourceApp: nil)
        store.add(.text("b"), sourceApp: nil)
        store.add(.text("a"), sourceApp: nil)
        #expect(store.items.map(\.text) == ["a", "b"])
    }

    @Test func limitKeepsPinnedItems() {
        let store = ClipboardStore(folder: folder)
        store.limit = 2
        let pinned = store.add(.text("keep me"), sourceApp: nil)!
        store.pin(pinned.id, slot: 1)
        for text in ["1", "2", "3"] { store.add(.text(text), sourceApp: nil) }
        #expect(store.items.map(\.text) == ["3", "2", "keep me"])
        #expect(store.item(inSlot: 1)?.text == "keep me")
    }

    @Test func pinningTakesTheSlotFromAnotherItem() {
        let store = ClipboardStore(folder: folder)
        let first = store.add(.text("first"), sourceApp: nil)!
        let second = store.add(.text("second"), sourceApp: nil)!
        store.pin(first.id, slot: 3)
        store.pin(second.id, slot: 3)
        #expect(store.item(inSlot: 3)?.id == second.id)
        #expect(store.items.first { $0.id == first.id }?.pinnedSlot == nil)
    }

    @Test func historyPersistsAndClearKeepsPins() {
        let store = ClipboardStore(folder: folder)
        let pinned = store.add(.link("https://example.com"), sourceApp: "com.apple.Safari")!
        store.pin(pinned.id, slot: 2)
        store.add(.text("temp"), sourceApp: nil)
        #expect(ClipboardStore(folder: folder).items == store.items)

        store.clearUnpinned()
        #expect(store.items.map(\.text) == ["https://example.com"])
    }

    @Test func imagesAreDedupedAndCleanedUp() throws {
        let store = ClipboardStore(folder: folder)
        let png = try #require(NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: 2, pixelsHigh: 2, bitsPerSample: 8,
                                                samplesPerPixel: 4, hasAlpha: true, isPlanar: false, colorSpaceName: .deviceRGB,
                                                bytesPerRow: 0, bitsPerPixel: 0)?.representation(using: .png, properties: [:]))
        let image = try #require(store.add(.image(png), sourceApp: nil))
        store.add(.image(png), sourceApp: nil)
        #expect(store.items.count == 1)
        let file = try #require(store.imageURL(for: image))
        #expect(FileManager.default.fileExists(atPath: file.path))

        store.remove(image.id)
        #expect(!FileManager.default.fileExists(atPath: file.path))
    }
}
