import AppKit
import CryptoKit
import Observation
import os

private let log = Logger(subsystem: "dev.superdock.SuperDock", category: "clipboard")

struct ClipItem: Codable, Identifiable, Equatable {
    enum Kind: String, Codable, CaseIterable {
        case text, link, color, image, file
    }

    var id = UUID()
    var kind: Kind
    /// Text, link or color value; file paths joined by newlines. nil for images.
    var text: String?
    /// File name of the PNG in the store's images folder (named by content hash, so duplicates share it).
    var imageFile: String?
    var date = Date()
    var sourceApp: String?    // bundle id of the app that was frontmost when copied
    var pinnedSlot: Int?      // 1–9

    var fileURLs: [URL] {
        kind == .file ? (text ?? "").split(separator: "\n").map { URL(fileURLWithPath: String($0)) } : []
    }
}

/// Reads the pasteboard into something worth keeping, or nil.
enum ClipboardCapture {
    enum Content: Equatable {
        case text(String), link(String), color(String), image(Data), files([URL])
    }

    /// Markers from nspasteboard.org: password managers set Concealed, and apps set Transient/AutoGenerated for
    /// data that shouldn't be remembered. Items carrying any of them are never read, let alone stored.
    static let skippedTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"), .init("org.nspasteboard.AutoGeneratedType")
    ]
    static let maxTextLength = 100_000
    static let maxImageBytes = 20_000_000

    static func read(_ pasteboard: NSPasteboard) -> Content? {
        let types = Set(pasteboard.types ?? [])
        guard types.isDisjoint(with: skippedTypes) else { return nil }

        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            return .files(urls)
        }
        if let png = imageData(pasteboard) {
            return png.count <= maxImageBytes ? .image(png) : nil
        }
        if let string = pasteboard.string(forType: .string), !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            return classify(String(string.prefix(maxTextLength)))
        }
        return nil
    }

    static func classify(_ string: String) -> Content {
        let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
        // Require the # so plain numbers like 123456 stay text.
        if trimmed.hasPrefix("#"), [4, 7, 9].contains(trimmed.count), trimmed.dropFirst().allSatisfy(\.isHexDigit) {
            return .color(trimmed)
        }
        if !trimmed.contains(where: \.isWhitespace), let url = URL(string: trimmed),
           let scheme = url.scheme?.lowercased(), ["http", "https", "mailto"].contains(scheme), url.host() != nil || scheme == "mailto" {
            return .link(trimmed)
        }
        return .text(string)
    }

    private static func imageData(_ pasteboard: NSPasteboard) -> Data? {
        if let png = pasteboard.data(forType: .png) { return png }
        guard let tiff = pasteboard.data(forType: .tiff) else { return nil }
        return NSBitmapImageRep(data: tiff)?.representation(using: .png, properties: [:])
    }
}

/// Clipboard history, saved to Application Support. Pinned items are kept regardless of the history limit.
@MainActor @Observable
final class ClipboardStore {
    static let shared = ClipboardStore(folder: URL.applicationSupportDirectory.appending(path: "SuperDock/Clipboard"))

    private(set) var items: [ClipItem]
    @ObservationIgnored var limit = 200
    @ObservationIgnored private let folder: URL

    private var historyFile: URL { folder.appending(path: "history.json") }
    private var imagesFolder: URL { folder.appending(path: "images") }

    init(folder: URL) {
        self.folder = folder
        items = JSONFile.load([ClipItem].self, from: folder.appending(path: "history.json")) ?? []
    }

    /// Adds new content at the top. Copying the same thing again moves the existing item up instead of duplicating it.
    @discardableResult
    func add(_ content: ClipboardCapture.Content, sourceApp: String?) -> ClipItem? {
        var item: ClipItem
        switch content {
        case .text(let text): item = ClipItem(kind: .text, text: text)
        case .link(let text): item = ClipItem(kind: .link, text: text)
        case .color(let text): item = ClipItem(kind: .color, text: text)
        case .files(let urls): item = ClipItem(kind: .file, text: urls.map(\.path).joined(separator: "\n"))
        case .image(let data):
            let name = SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined() + ".png"
            do {
                try FileManager.default.createDirectory(at: imagesFolder, withIntermediateDirectories: true)
                let file = imagesFolder.appending(path: name)
                if !FileManager.default.fileExists(atPath: file.path) { try data.write(to: file, options: .atomic) }
            } catch {
                log.error("Couldn't save copied image: \(error)")
                return nil
            }
            item = ClipItem(kind: .image, imageFile: name)
        }
        item.sourceApp = sourceApp

        var next = items
        if let existing = next.firstIndex(where: { $0.kind == item.kind && $0.text == item.text && $0.imageFile == item.imageFile }) {
            item.id = next[existing].id
            item.pinnedSlot = next[existing].pinnedSlot
            next.remove(at: existing)
        }
        next.insert(item, at: 0)
        commit(trimmed(next))
        return item
    }

    func remove(_ id: ClipItem.ID) {
        commit(items.filter { $0.id != id })
    }

    /// Clears history but keeps pinned items.
    func clearUnpinned() {
        commit(items.filter { $0.pinnedSlot != nil })
    }

    /// Puts the item in `slot` (taking it from whichever item held it), or unpins with nil.
    func pin(_ id: ClipItem.ID, slot: Int?) {
        commit(items.map { item in
            var item = item
            if item.id == id { item.pinnedSlot = slot } else if slot != nil, item.pinnedSlot == slot { item.pinnedSlot = nil }
            return item
        })
    }

    func item(inSlot slot: Int) -> ClipItem? {
        items.first { $0.pinnedSlot == slot }
    }

    func imageURL(for item: ClipItem) -> URL? {
        item.imageFile.map { imagesFolder.appending(path: $0) }
    }

    /// Keeps every pinned item plus the newest `limit` unpinned ones.
    private func trimmed(_ list: [ClipItem]) -> [ClipItem] {
        var unpinned = 0
        return list.filter { item in
            if item.pinnedSlot != nil { return true }
            unpinned += 1
            return unpinned <= limit
        }
    }

    private func commit(_ next: [ClipItem]) {
        // Delete image files nothing refers to any more.
        let kept = Set(next.compactMap(\.imageFile))
        for name in Set(items.compactMap(\.imageFile)).subtracting(kept) {
            do {
                try FileManager.default.removeItem(at: imagesFolder.appending(path: name))
            } catch {
                log.error("Couldn't delete old clipboard image: \(error)")
            }
        }
        items = next
        JSONFile.save(items, to: historyFile)
    }
}
